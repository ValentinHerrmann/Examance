/** Click-to-source and the editor's cursor in the pages for one compiled preview (both panes of the exercise editor, the Exam step's preview; issue #347). Owns the last result per pane, the caret and selection marks, and the template tooltip. */
import { caretFor, hasGlyphs, isClickable, resolveClick, selectionFor, wordAt, type ClickTarget, type PageClick, type PageMarks, type SyncedResult } from './clickToSource';

type BodyOf = (exerciseId: string | null) => string | undefined;
/** An editor selection in one exercise body: 1-based lines, 0-based columns. */
export interface BodySelection {
  exerciseId: string | null;
  anchor: { line: number; column: number };
  head: { line: number; column: number };
}

export class PreviewSync {
  /** Caret and selection per pane id, drawn by the pages (`PdfEmbedViewer` `marks`). */
  marks = $state.raw<Record<string, PageMarks | null>>({});
  /** Where the "generated by the template" tooltip shows, or null. */
  tip = $state.raw<{ x: number; y: number } | null>(null);
  private results = new Map<string, SyncedResult>();
  private selection: BodySelection | null = null;
  private bodyOf: BodyOf = () => undefined;
  /** Bumped by every new result and `reset()`: a click resolved against an older one is dropped. */
  private seq = 0;

  /** A new PDF in `paneId` (or none): the marks follow it, the next click resolves against it. */
  setResult(paneId: string, result: SyncedResult | undefined): void {
    this.seq++;
    if (result) this.results.set(paneId, result);
    else this.results.delete(paneId);
    this.refresh();
  }

  reset(): void {
    this.seq++;
    this.results.clear();
    this.selection = null;
    this.marks = {};
    this.tip = null;
  }

  clickable(paneId: string): boolean {
    return isClickable(this.results.get(paneId));
  }

  /** Whether `paneId` has exact glyph positions (the browser engine): the cursor shows there and typing on the page works. */
  editable(paneId: string): boolean {
    return hasGlyphs(this.results.get(paneId));
  }

  /** The editor's selection moved (or the text changed): the marks follow it; `bodyOf` reads the bodies as they are now. */
  select(selection: BodySelection | null, bodyOf: BodyOf): void {
    this.selection = selection;
    this.bodyOf = bodyOf;
    this.refresh();
  }

  private refresh(): void {
    const sel = this.selection;
    const next: Record<string, PageMarks | null> = {};
    for (const [paneId, result] of this.results) {
      if (!sel || !hasGlyphs(result)) continue;
      const empty = sel.anchor.line === sel.head.line && sel.anchor.column === sel.head.column;
      next[paneId] = {
        caret: caretFor(result, sel.exerciseId, sel.head.line, sel.head.column, this.bodyOf),
        boxes: empty ? [] : selectionFor(result, sel.exerciseId, sel.anchor, sel.head, this.bodyOf),
      };
    }
    this.marks = next;
  }

  /** The source under a click; a template hit opens the tooltip at the click (`tip: false` for silent lookups such as a drag). `bodyOf` returns a marked exercise's LaTeX (by id; null for a document with one unnamed body). */
  async click(paneId: string, click: PageClick, bodyOf: BodyOf, tip = true): Promise<ClickTarget | null> {
    const result = this.results.get(paneId);
    if (!result || !isClickable(result)) return null;
    const seq = this.seq;
    // The engine's glyph positions make the text under the click known; only other results read it from the PDF.
    const word = hasGlyphs(result) ? null : await wordAt(result.pdfBytes, click);
    if (seq !== this.seq) return null;
    const target = resolveClick(result, click, word, bodyOf);
    if (tip) this.tip = target?.kind === 'template' ? { x: click.clientX, y: click.clientY } : null;
    return target;
  }
}
