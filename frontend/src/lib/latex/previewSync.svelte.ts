/** Click-to-source and the editor's cursor in the pages for one compiled preview (both panes of the exercise editor, the Exam step's preview; issue #347). Owns the result shown per pane, the caret and selection marks, and the template tooltip. */
import { caretFor, glyphTarget, hasGlyphs, isClickable, resolveClick, selectionFor, wordAt, type ClickTarget, type PageClick, type PageMarks, type SyncedResult } from './clickToSource';
import { toCompiled, toCurrent, type TextPos } from './inlineEdit/textMap';

type BodyOf = (exerciseId: string | null) => string | undefined;
/** An editor selection in one exercise body: 1-based lines, 0-based columns. */
export interface BodySelection {
  exerciseId: string | null;
  anchor: { line: number; column: number };
  head: { line: number; column: number };
}

/** A result with what it was compiled from. */
interface Shown {
  result: SyncedResult;
  /** The bodies as compiled, so positions map to the text typed since (`textMap.ts`); absent: the current text. */
  compiled?: BodyOf;
}

export class PreviewSync {
  /** Caret and selection per pane id, drawn by the pages (`PdfEmbedViewer` `marks`). */
  marks = $state.raw<Record<string, PageMarks | null>>({});
  /** Where the "generated by the template" tooltip shows, or null. */
  tip = $state.raw<{ x: number; y: number } | null>(null);
  private results = new Map<string, Shown>();
  /** Results whose PDF is not on screen yet, per pane: they take over once the viewer shows that URL (`shown`). */
  private waiting = new Map<string, Shown & { url: string }>();
  private shownUrl = new Map<string, string>();
  private selection: BodySelection | null = null;
  private bodyOf: BodyOf = () => undefined;
  /** Bumped when the caret moved through a click in the code editor: the page caret pulses once. */
  private flash = 0;
  /** Bumped by every new result and `reset()`: a click resolved against an older one is dropped. */
  private seq = 0;

  /** A new PDF in `paneId` (or none). With `url` it counts once the viewer shows that PDF, so a click always resolves against the pages on screen; `compiled` gives the bodies it was compiled from. */
  setResult(paneId: string, result: SyncedResult | undefined, opts: { url?: string; compiled?: BodyOf } = {}): void {
    if (result && opts.url && this.shownUrl.get(paneId) !== opts.url) {
      this.waiting.set(paneId, { result, compiled: opts.compiled, url: opts.url });
      return;
    }
    this.waiting.delete(paneId);
    this.apply(paneId, result ? { result, compiled: opts.compiled } : undefined);
  }

  /** The viewer of `paneId` now shows `url`. */
  shown(paneId: string, url: string): void {
    this.shownUrl.set(paneId, url);
    const next = this.waiting.get(paneId);
    if (next?.url !== url) return;
    this.waiting.delete(paneId);
    this.apply(paneId, next);
  }

  private apply(paneId: string, shown: Shown | undefined): void {
    this.seq++;
    if (shown) this.results.set(paneId, shown);
    else this.results.delete(paneId);
    this.refresh();
  }

  reset(): void {
    this.seq++;
    this.results.clear();
    this.waiting.clear();
    this.shownUrl.clear();
    this.selection = null;
    this.marks = {};
    this.tip = null;
  }

  clickable(paneId: string): boolean {
    return isClickable(this.results.get(paneId)?.result);
  }

  /** Whether `paneId` has exact glyph positions (the browser engine): the cursor shows there and typing on the page works. */
  editable(paneId: string): boolean {
    return hasGlyphs(this.results.get(paneId)?.result);
  }

  /** The editor's selection moved (or the text changed): the marks follow it; `bodyOf` reads the bodies as they are now. `flash` (a click in the code editor) makes the page caret pulse once. */
  select(selection: BodySelection | null, bodyOf: BodyOf, flash = false): void {
    this.selection = selection;
    this.bodyOf = bodyOf;
    if (flash) this.flash++;
    this.refresh();
  }

  /** A position in the current text as one in the text `shown` was compiled from. */
  private compiledPos(shown: Shown, exerciseId: string | null, pos: TextPos): TextPos {
    const compiled = shown.compiled?.(exerciseId);
    const current = this.bodyOf(exerciseId);
    return compiled === undefined || current === undefined ? pos : toCompiled(compiled, current, pos);
  }

  private refresh(): void {
    const sel = this.selection;
    const next: Record<string, PageMarks | null> = {};
    for (const [paneId, shown] of this.results) {
      if (!sel || !hasGlyphs(shown.result)) continue;
      const empty = sel.anchor.line === sel.head.line && sel.anchor.column === sel.head.column;
      const head = this.compiledPos(shown, sel.exerciseId, sel.head);
      const anchor = this.compiledPos(shown, sel.exerciseId, sel.anchor);
      const compiledOf: BodyOf = (id) => shown.compiled?.(id) ?? this.bodyOf(id);
      next[paneId] = {
        caret: caretFor(shown.result, sel.exerciseId, head.line, head.column, compiledOf),
        boxes: empty ? [] : selectionFor(shown.result, sel.exerciseId, anchor, head, compiledOf),
        flash: this.flash,
      };
    }
    this.marks = next;
  }

  /** The source under a click, in the text as it is now; a template hit opens the tooltip at the click (`tip: false` for silent lookups such as a drag). `bodyOf` returns a marked exercise's LaTeX (by id; null for a document with one unnamed body). */
  async click(paneId: string, click: PageClick, bodyOf: BodyOf, tip = true): Promise<ClickTarget | null> {
    const shown = this.results.get(paneId);
    if (!shown || !isClickable(shown.result)) return null;
    const seq = this.seq;
    const compiledOf: BodyOf = (id) => shown.compiled?.(id) ?? bodyOf(id);
    // The engine's character positions make the text under the click known; elsewhere (other results, formulas, rebuilt text) the word is read from the PDF.
    let target = hasGlyphs(shown.result) ? glyphTarget(shown.result, click, compiledOf) : null;
    if (!target) {
      const word = await wordAt(shown.result.pdfBytes, click);
      if (seq !== this.seq) return null;
      target = resolveClick(shown.result, click, word, compiledOf);
    }
    if (target?.kind === 'source') {
      const compiled = shown.compiled?.(target.exerciseId);
      const current = bodyOf(target.exerciseId);
      if (compiled !== undefined && current !== undefined) target = { ...target, ...toCurrent(compiled, current, target) };
    }
    if (tip) this.tip = target?.kind === 'template' ? { x: click.clientX, y: click.clientY } : null;
    return target;
  }
}
